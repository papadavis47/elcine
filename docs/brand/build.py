"""Build elcine logo assets with text outlined from the bundled fonts.

Run from repo root:
    uv run --with fonttools --with uharfbuzz python docs/brand/build.py

Writes:
    docs/brand/elcine-banner-{light,dark}.svg   README banners
    src/components/wordmark.ts                  header wordmark path data
"""

from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.teePen import TeePen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "docs/brand"
FONTS = BRAND / "fonts"

WORDMARK = (FONTS / "DMSans[opsz,wght].ttf", {"opsz": 40, "wght": 600})
SUBTITLE = (FONTS / "NotoSans[wdth,wght].ttf", {"wdth": 100, "wght": 400})


def outline(font_spec, text, size, tracking_em=0.0, x0=0.0, baseline=0.0):
    """Shape text (with kerning); return (svg path d, advance width, (xmin, ymin, xmax, ymax))."""
    path, loc = font_spec
    blob = hb.Blob.from_file_path(str(path))
    face = hb.Face(blob)
    font = hb.Font(face)
    font.set_variations(loc)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})

    tt = TTFont(path)
    upem = tt["head"].unitsPerEm
    glyphs = tt.getGlyphSet(location=loc)
    s = size / upem
    track = tracking_em * size

    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    bounds = BoundsPen(glyphs)
    x = x0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = tt.getGlyphName(info.codepoint)
        gx = x + pos.x_offset * s
        gy = baseline - pos.y_offset * s
        glyphs[name].draw(TransformPen(TeePen(pen, bounds), (s, 0, 0, -s, gx, gy)))
        x += pos.x_advance * s + track
    return pen.getCommands(), x - x0 - track, bounds.bounds


def icon_body():
    svg = (BRAND / "elcine-icon.svg").read_text()
    return svg[svg.index(">") + 1 : svg.rindex("</svg>")]


def banner(color):
    # proportions match the approved mock: icon 96, name 66, subtitle 14 (x2)
    icon, gap, pad = 192, 44, 48
    name_size, sub_size = 132, 28
    tx = pad + icon + gap
    # name + gap + subtitle, block roughly centered on the icon
    name_base = pad + 112
    sub_base = name_base + 24 + sub_size + 12
    name_d, name_w, _ = outline(WORDMARK, "elcine", name_size, -0.03, tx, name_base)
    sub_d, sub_w, _ = outline(SUBTITLE, "YOUR FILM COLLECTION", sub_size, 0.2, tx + 2, sub_base)
    width = round(tx + max(name_w, sub_w) + pad)
    height = icon + 2 * pad
    scale = icon / 512
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="elcine, your film collection">
<g transform="translate({pad} {pad}) scale({scale})">{icon_body()}</g>
<path fill="{color}" d="{name_d}"/>
<path fill="{color}" fill-opacity=".6" d="{sub_d}"/>
</svg>
"""


def wordmark_ts():
    d, _, (x0, y0, x1, y1) = outline(WORDMARK, "elcine", 100, -0.03)
    box = f"{x0:.2f} {y0:.2f} {x1 - x0:.2f} {y1 - y0:.2f}"
    return (
        "// Generated by docs/brand/build.py. Do not edit.\n"
        '// "elcine" in DM Sans SemiBold, outlined.\n'
        f'export const WORDMARK_VIEWBOX = "{box}";\n'
        f'export const WORDMARK_PATH =\n  "{d}";\n'
    )


if __name__ == "__main__":
    (BRAND / "elcine-banner-light.svg").write_text(banner("#1b1a17"))
    (BRAND / "elcine-banner-dark.svg").write_text(banner("#f3efe6"))
    (ROOT / "src/components/wordmark.ts").write_text(wordmark_ts())
    print("ok")
